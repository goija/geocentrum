#!/usr/bin/env bash
# ==============================================================================
# VORTEX OS / GEOCENTRUM — Asset Manifest Builder & Directory Scanner
# Version: 1.58.0
# Description: Automatically scans repository directories (assets, cockpittools,
#              images, systeemdiagnose, txt, root) and generates `assets/assets_manifest.js`
#              as well as writing a log entry to `txt/geocentrum_manifest_build.log`.
# ==============================================================================

set -e

# Base directories
PROJECT_ROOT="$(pwd)"
ASSETS_DIR="${PROJECT_ROOT}/assets"
TOOLS_DIR="${PROJECT_ROOT}/cockpittools"
IMAGES_DIR="${PROJECT_ROOT}/images"
DIAG_DIR="${PROJECT_ROOT}/systeemdiagnose"
TXT_DIR="${PROJECT_ROOT}/txt"

MANIFEST_FILE="${ASSETS_DIR}/assets_manifest.js"
LOG_FILE="${TXT_DIR}/geocentrum_manifest_build.log"

# Ensure directories exist
mkdir -p "${ASSETS_DIR}" "${TOOLS_DIR}" "${IMAGES_DIR}" "${DIAG_DIR}" "${TXT_DIR}"

BUILD_TIMESTAMP=$(date -u +"%Y-%m-%dT%H:%M:%SZ")
LOCAL_TIME=$(date +"%Y-%m-%d %H:%M:%S %Z")

echo "======================================================================"
echo "🚀 VORTEX OS Asset Manifest Builder v1.58.0"
echo "Build Timestamp: ${LOCAL_TIME}"
echo "======================================================================"

# Start building assets_manifest.js
cat << 'EOF' > "${MANIFEST_FILE}"
/**
 * VORTEX OS / GEOCENTRUM — Assets Manifest
 * Auto-generated by build_geocentrum_assets.sh
 */

export const VORTEX_ASSETS_MANIFEST = {
  version: "1.58.0",
EOF

echo "  buildTimestamp: \"${BUILD_TIMESTAMP}\"," >> "${MANIFEST_FILE}"

# Function to scan directory and output JSON array
scan_dir_to_json() {
  local target_dir="$1"
  local indent="$2"
  
  if [ ! -d "$target_dir" ]; then
    echo "[]"
    return
  fi

  local files=()
  while IFS= read -r -d '' file; do
    rel_path=$(basename "$file")
    files+=("\"${rel_path}\"")
  done < <(find "$target_dir" -maxdepth 2 -type f ! -name ".*" -print0 | sort -z)

  if [ ${#files[@]} -eq 0 ]; then
    echo "[]"
  else
    local joined
    joined=$(IFS=, ; echo "${files[*]}")
    echo "[ ${joined} ]"
  fi
}

echo "Scanning directories..."

echo "  structure: {" >> "${MANIFEST_FILE}"

echo -n "    assets: " >> "${MANIFEST_FILE}"
scan_dir_to_json "${ASSETS_DIR}" "    " >> "${MANIFEST_FILE}"
echo "," >> "${MANIFEST_FILE}"

echo -n "    cockpittools: " >> "${MANIFEST_FILE}"
scan_dir_to_json "${TOOLS_DIR}" "    " >> "${MANIFEST_FILE}"
echo "," >> "${MANIFEST_FILE}"

echo -n "    images: " >> "${MANIFEST_FILE}"
scan_dir_to_json "${IMAGES_DIR}" "    " >> "${MANIFEST_FILE}"
echo "," >> "${MANIFEST_FILE}"

echo -n "    systeemdiagnose: " >> "${MANIFEST_FILE}"
scan_dir_to_json "${DIAG_DIR}" "    " >> "${MANIFEST_FILE}"
echo "," >> "${MANIFEST_FILE}"

echo -n "    txt: " >> "${MANIFEST_FILE}"
scan_dir_to_json "${TXT_DIR}" "    " >> "${MANIFEST_FILE}"
echo "" >> "${MANIFEST_FILE}"

echo "  }," >> "${MANIFEST_FILE}"

# Write metadata section
cat << EOF >> "${MANIFEST_FILE}"
  metadata: {
    system: "VORTEX OS / Geocentrum Framework",
    activeVectors: ["51.40° NO (Aldebaran)", "245.91° WZW (Mercurius/Eclips)"],
    anchors: {
      poolanker_p: "52.2500° N, 5.2200° E",
      n2_core: "47.2500° N, 1.8500° E",
      exit_biskaje: "46.2500° N, -1.2500° E",
      eclips_landfall: "43.5500° N, -6.5000° E"
    }
  }
};
EOF

echo "✓ Manifest generated successfully: ${MANIFEST_FILE}"

# Append to build log
cat << EOF >> "${LOG_FILE}"
[${LOCAL_TIME}] SUCCESS: Asset manifest built successfully.
  - Manifest Path: ${MANIFEST_FILE}
  - Timestamp: ${BUILD_TIMESTAMP}
EOF

echo "✓ Log updated: ${LOG_FILE}"
echo "======================================================================"
echo "Build complete!"
EOF
